for a,(city,street,h) in MANUAL.items():
    if cache.get(a): continue
    hb=re.split(r'\s*к|/',h)[0]
    tries=[{'q':f'{city}, {street}, {h}'},{'street':f'{h} {street}','city':city},{'street':f'{hb} {street}','city':city},
           {'q':f'{city}, {street}, {hb}'},{'q':f'{street}, {city}'}]
    for i,p in enumerate(tries):
        res=q(p)
        if res:
            cache[a]={'lat':res[0],'lon':res[1],'name':res[2],'level':'m%d'%i}; break
    print(('OK ' if cache.get(a) else 'MISS'), a, '->', cache.get(a,{}) and cache[a]['name'][:90])
