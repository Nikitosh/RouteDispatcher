def line_chart(s, x, y, w, h, cats, series, colors, ymin=None, ymax=None, labels=None):
    cd = CategoryChartData()
    cd.categories = cats
    for name, vals in series:
        cd.add_series(name, vals)
    ch = s.shapes.add_chart(XL_CHART_TYPE.LINE, I(x), I(y), I(w), I(h), cd).chart
    style_chart(ch)
    ch.has_title = False
    ch.has_legend = len(series) > 1
    if ch.has_legend:
        ch.legend.position = XL_LEGEND_POSITION.TOP; ch.legend.include_in_layout = False; ch.legend.font.size = P(10.5)
    for ser, col in zip(ch.plots[0].series, colors):
        ser.format.line.color.rgb = col; ser.format.line.width = P(2.75); ser.smooth = True
        ser.marker.style = None
    va = ch.value_axis; va.has_major_gridlines = False; va.tick_labels.font.size = P(10); va.format.line.color.rgb = LGREY
    if ymin is not None: va.minimum_scale = ymin
    if ymax is not None: va.maximum_scale = ymax
    if labels: va.tick_labels.number_format = labels; va.tick_labels.number_format_is_linked = False
    ca = ch.category_axis; ca.tick_labels.font.size = P(10); ca.format.line.color.rgb = GREY
    return ch


