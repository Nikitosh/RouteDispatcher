# ---------- клонирование элементов шаблона ----------
def clone(src_slide, shp, dst_slide):
    el = copy.deepcopy(shp._element)
    for node in el.iter():
        for attr in (qn('r:embed'), qn('r:link'), qn('r:id')):
            rid = node.get(attr)
            if rid and rid in src_slide.part.rels:
                rel = src_slide.part.rels[rid]
                node.set(attr, dst_slide.part.relate_to(rel.target_part, rel.reltype))
    dst_slide.shapes._spTree.insert_element_before(el, 'p:extLst')
    return el


def retext(slide, old, lines):
    """Заменить текст клонированного блока, сохранив оформление первого run."""
    for shp in slide.shapes:
        if shp.has_text_frame and shp.text_frame.text.replace('\n', '').replace('\x0b', '') == old:
            tf = shp.text_frame
            p0 = tf.paragraphs[0]._p
            r0 = copy.deepcopy(p0.findall(qn('a:r'))[0])
            for p in list(tf.paragraphs)[1:]:
                p._p.getparent().remove(p._p)
            for e in list(p0):
                if e.tag in (qn('a:r'), qn('a:br')):
                    p0.remove(e)
            end = p0.find(qn('a:endParaRPr'))
            for i, ln in enumerate(lines):
                if i:
                    br = copy.deepcopy(r0); br.tag = qn('a:br')
                    for c in list(br):
                        if c.tag != qn('a:rPr'):
                            br.remove(c)
                    (end.addprevious(br) if end is not None else p0.append(br))
                r = copy.deepcopy(r0); r.find(qn('a:t')).text = ln
                (end.addprevious(r) if end is not None else p0.append(r))
            return shp
    raise KeyError(old)


def new_slide(kind='light'):
    s = prs.slides.add_slide(BLANK)
    for ph in list(s.placeholders):
        ph._element.getparent().remove(ph._element)
    s.kind = kind
    set_bg(s, {'light': 'FFFFFF', 'dark': '141414', 'bee': 'FFC800'}[kind])
    SLIDES.append(s)
    return s


def slide(kind, crumb, title, sub=None):
    s = new_slide(kind)
    dark = kind == 'dark'
    text(s, 0.36, 0.3, 9, 0.25, crumb, size=8.5, color=GREY if dark else MGREY)
    clone(T[8], LOGO, s)
