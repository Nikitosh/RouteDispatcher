def shots_row(s, items, y=1.65, h=4.55, gap=0.3, x0=0.36, w_total=12.6, cap_h=1.0, dark=False):
    """Несколько скриншотов в ряд с подписями под ними: [(файл, заголовок, текст, доля ширины)]."""
    widths = [it[3] if len(it) > 3 else 1 for it in items]
    unit = (w_total - gap * (len(items) - 1)) / sum(widths)
    x = x0
    for it, wk in zip(items, widths):
        w = unit * wk
        pic = image(s, SHOT(it[0]), x, y, w, h)
        pic.top = I(y)                                   # по верху: подписи на одной линии
        rounded(pic, 0.02)
        pic.line.color.rgb = LGREY if not dark else DGREY; pic.line.width = P(0.75)
        if it[1]:
            text(s, x, y + h + 0.12, w, 0.32, it[1], size=13.5, bold=True, color=WHITE if dark else BLACK)
        if it[2]:
            text(s, x, y + h + 0.45, w, cap_h, it[2], size=11, color=GREY if dark else DGREY)
        x += w + gap


