def first_legs(name):
    """(мин из дома, мин из офиса, км из дома, км из офиса) до первых адресов бригад плана."""
    L = open(os.path.join(OUTD, name, 'task.txt'), encoding='utf-8').read().split('\n')
    N, V, S = map(int, L[1].split())
    M = S + N
    veh = [l.split() for l in L[2 + N:2 + N + V]]
    rows, mats, q = L[2 + N + V:], [], 0
    for _ in range(4):
        T = [list(map(float, rows[q + i].split())) for i in range(M)]; q += M
        Dm = [list(map(float, rows[q + i].split())) for i in range(M)]; q += M
        mats.append((T, Dm))
    ans = _json.load(open(os.path.join(OUTD, name, 'answer.json')))
    h = o = hk = ok = n = 0
    for v, r in enumerate(ans['routes']):
        if not r:
            continue
        st, mode = int(veh[v][0]), int(veh[v][1])
        T, Dm = mats[mode]
        h += T[st][S + r[0]]; o += T[0][S + r[0]]; hk += Dm[st][S + r[0]]; ok += Dm[0][S + r[0]]; n += 1
    return h / n, o / n, hk, ok, n


