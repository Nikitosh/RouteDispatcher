def window_hours(a, b):
    """Часы (0 — 10:00) промежутка [a, b] минут от 10:00 по отсчётам раз в 15 мин: час встречается столько раз,
    сколько его четвертей попало в промежуток."""
    a, b = max(0.0, min(a, SHIFT - 1)), max(0.0, min(b, SHIFT - 1))
    return [int(t // 60) for t in range(int(a), int(b) + 1, 15)] or [int(a // 60)]


