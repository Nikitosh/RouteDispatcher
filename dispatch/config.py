def _option(oid, salt, share):
    """Клиент выбрал опцию — детерминированно по номеру заявки, одинаково при каждом запуске."""
    return zlib.crc32(f'{oid}:{salt}'.encode()) % 100 < share


def equipment_for(bk, hd='', oid=None):
    """Оборудование для заявки: {вид: штук}. Жюри: оборудование — дополнительная опция, которую выбирает клиент
    (роутер, приставка). Дозаказ оборудования — роутер (или приставка, если в подтипе ТВ); подключение — роутер у
    ROUTER_OPTION % клиентов и приставка, если в подтипе ТВ или у STB_OPTION %; замена роутера или приставки — она;
    остальной ремонт и аварии — ничего. Без номера заявки (oid=None) подключение считается с роутером."""
    h = (hd or '').lower()
    tv = re.search(r'\bтв\b|tve|приставк', h) is not None
    if bk == 'Дозаказ':
        return {'stb': 1} if tv and 'роутер' not in h else {'router': 1}
    if bk == 'Подключение':
        if oid is None:
            return {'router': 1, 'stb': 1} if tv else {'router': 1}
        out = {}
        if _option(oid, 'router', ROUTER_OPTION):
            out['router'] = 1
        if tv or _option(oid, 'stb', STB_OPTION):
            out['stb'] = 1
        return out
    if bk == 'Локальная заявка' and 'замена' in h:
        if 'роутер' in h:
            return {'router': 1}
        if tv:
            return {'stb': 1}
    return {}


