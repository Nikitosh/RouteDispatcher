def zone_of(lat, lon):
    """(район, доли загруженности по часам) для точки."""
    for name, (clat, clon), (a, b), share in ZONES:
        if ((lat - clat) / a) ** 2 + ((lon - clon) / b) ** 2 <= 1:
            return name, share
    return OUTSIDE


