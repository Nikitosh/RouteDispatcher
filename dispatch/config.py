def day_profile(weekday=None):
    """Пробки по часам для дня недели (0 — понедельник); без даты — средние будни."""
    return TRAFFIC_HOURS if weekday is None else TRAFFIC_DAYS[weekday]


def weekday_of(date):
    """День недели (0 — понедельник) из даты «17.08.2026» или «2026-08-17»; None, если даты нет или она не разобралась."""
    import datetime
    for fmt in ('%d.%m.%Y', '%Y-%m-%d'):
        try:
            return datetime.datetime.strptime(str(date).strip()[:10], fmt).weekday()
        except ValueError:
            pass
    return None


def traffic_ratio(a, b, share=None, profile=None):
    """Во сколько раз дорога на машине в промежутке [a, b] (минуты от 10:00) дольше средней по городу за день
    10:00–22:00 средних будней. share — доля загруженности района по часам (zone_of; для поездки — среднее по её
    концам): в районе коэффициент часа 1 + (профиль − 1) · доля. profile — пробки по часам дня (day_profile)."""
    mean = sum(TRAFFIC_HOURS) / len(TRAFFIC_HOURS)
    hours = window_hours(a, b)
    P = profile or TRAFFIC_HOURS
    f = (lambda h: P[h]) if share is None else (lambda h: 1 + (P[h] - 1) * share[h])
    return sum(f(h) for h in hours) / len(hours) / mean


@dataclass
class TravelSettings:
    """Время в пути = OSRM × коэффициент пробок + подход к заявке (парковка, дверь, домофон, лифт).
    Коэффициент 1,3 для машины сверен вручную по Яндекс Картам. hourly — поправка машины на час дня (TRAFFIC_HOURS):
    поездка к заявке считается в часы её окна, в среднем за день коэффициент тот же."""
